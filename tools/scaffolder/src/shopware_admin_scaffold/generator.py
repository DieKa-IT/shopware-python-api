"""Create a complete, deterministic source plan with no filesystem writes."""

import ast
import hashlib
import json
import re
from dataclasses import dataclass, replace

from . import RUNTIME_REQUIREMENT, ScaffoldError, __version__
from .catalog import Catalog, EntitySpec, FieldSpec, Json, object_value
from .naming import (
    FIELD_RESERVED,
    MODEL_RESERVED,
    SET_RESERVED,
    identifier,
    package_name,
    pascal_case,
    pluralize,
    snake_case,
)

HEADER = "# Generated by shopware-admin-scaffold. Do not edit.\n"
OWNER = "shopware-admin-scaffold"
MANIFEST = "_generated/manifest.json"


def digest(content: str) -> str:
    return hashlib.sha256(content.encode("utf-8")).hexdigest()


def json_text(value: object) -> str:
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=True) + "\n"


@dataclass(frozen=True)
class NamedEntity:
    spec: EntitySpec
    class_name: str
    module_name: str
    set_name: str
    fields: tuple[tuple[str, FieldSpec], ...]


@dataclass(frozen=True)
class FilePlan:
    generated: dict[str, str]
    public: dict[str, str]
    manifest: Json
    diagnostics: tuple[str, ...]


def _override_field(field: FieldSpec, overrides: Json, label: str) -> FieldSpec:
    for option in overrides:
        if option not in {"name", "nullable", "writable", "required_on_create"}:
            raise ScaffoldError(f"{label}: unknown field override {option!r}")
    values: Json = {}
    for option in ("nullable", "writable", "required_on_create"):
        if option in overrides:
            if type(overrides[option]) is not bool:
                raise ScaffoldError(f"{label}.{option} must be a boolean")
            values[option] = overrides[option]
    if field.target and values:
        raise ScaffoldError(f"{label}: association flags cannot be overridden")
    if field.wire_name == "id" and (values.get("nullable") or values.get("required_on_create")):
        raise ScaffoldError(f"{label}: primary id must be nonnullable and optional on create")
    updated = replace(field, **values)
    if updated.required_on_create and not updated.writable:
        raise ScaffoldError(f"{label}: read-only fields cannot be required on create")
    return updated


def render(
    catalog: Catalog,
    selected: tuple[EntitySpec, ...],
    package: str,
    context: str | None = None,
    entity_overrides: Json | None = None,
    field_overrides: Json | None = None,
    schema_hashes: Json | None = None,
) -> FilePlan:
    package_name(package)
    if context:
        identifier(context, "context class", MODEL_RESERVED | {"Context"})
    entity_overrides = entity_overrides or {}
    field_overrides = field_overrides or {}
    catalog_names = {entity.name for entity in catalog.entities}
    for name in set(entity_overrides) | set(field_overrides):
        if name not in catalog_names:
            raise ScaffoldError(f"Override refers to unknown entity {name!r}")
    diagnostics = list(catalog.diagnostics)
    named: list[NamedEntity] = []
    for spec in selected:
        options = object_value(entity_overrides.get(spec.name, {}), "Entity overrides")
        if set(options) - {"class_name", "set_name"}:
            raise ScaffoldError(f"{spec.name}: unknown entity naming override")
        class_name = options.get("class_name", pascal_case(spec.schema_name))
        if not isinstance(class_name, str):
            raise ScaffoldError("Class names must be strings")
        set_name = options.get("set_name", pluralize(snake_case(class_name)))
        if not isinstance(set_name, str):
            raise ScaffoldError("Entity-set names must be strings")
        identifier(class_name, "model class", MODEL_RESERVED)
        identifier(set_name, "entity set", SET_RESERVED)
        module_name = identifier(snake_case(class_name), "model module", {"context"})
        overrides = object_value(field_overrides.get(spec.name, {}), "Field overrides")
        unknown = set(overrides) - {field.wire_name for field in spec.fields}
        if unknown:
            raise ScaffoldError(f"{spec.name}: overrides refer to unknown fields {sorted(unknown)}")
        fields: list[tuple[str, FieldSpec]] = []
        for field in spec.fields:
            label = f"{spec.name}.{field.wire_name}"
            option = object_value(overrides.get(field.wire_name, {}), label)
            field = _override_field(field, option, label)
            python_name = option.get("name", snake_case(field.wire_name))
            if not isinstance(python_name, str):
                raise ScaffoldError(f"{label}: field name must be a string")
            identifier(python_name, "field name", FIELD_RESERVED)
            if option:
                diagnostics.append(f"{label}: applied overrides {', '.join(sorted(option))}")
            fields.append((python_name, field))
        if len({name for name, _ in fields}) != len(fields):
            raise ScaffoldError(f"{spec.name}: conflicting Python field names")
        named.append(NamedEntity(spec, class_name, module_name, set_name, tuple(fields)))
    for attribute in ("class_name", "module_name", "set_name"):
        values = [getattr(entity, attribute) for entity in named]
        if len(set(values)) != len(values):
            raise ScaffoldError(f"Conflicting model {attribute}; supply naming overrides")
    classes = {entity.class_name for entity in named}
    if classes & {name + "Base" for name in classes}:
        raise ScaffoldError("Public model names collide with generated base names")
    if context in classes or (context and context + "Base" in classes):
        raise ScaffoldError("Context name collides with a model")
    by_name = {entity.spec.name: entity for entity in named}
    public = {"__init__.py": "", "models/__init__.py": ""}
    generated = {"_generated/__init__.py": HEADER}
    imports: set[str] = {"Entity"}
    extras: set[str] = set()
    public_imports: set[str] = set()
    declarations: list[str] = []
    for entity in named:
        lines = [
            f"class {entity.class_name}Base(Entity):",
            f"    __entity__ = {entity.spec.name!r}",
            f"    __route__ = {entity.spec.route!r}",
        ]
        for python_name, field in entity.fields:
            if field.target:
                target = by_name.get(field.target)
                if target is None:
                    diagnostics.append(
                        f"{entity.spec.name}.{field.wire_name}: association target "
                        f"{field.target!r} not selected; omitted"
                    )
                    continue
                descriptor = "ToMany" if field.many else "ToOne"
                factory = "to_many" if field.many else "to_one"
                value_type = f"public_{target.module_name}.{target.class_name}"
                public_imports.add(
                    f"from ..models import {target.module_name} "
                    f"as public_{target.module_name}  # noqa: E402"
                )
            else:
                descriptor, factory = "Field", "api_field"
                value_type = field.value_type
                if field.nullable and value_type not in {"Any", "None"}:
                    value_type += " | None"
                extras.update(re.findall(r"\b(?:Any|datetime)\b", value_type))
            imports.update((descriptor, factory))
            lines.extend(["", f"    {python_name}: {descriptor}[{value_type}] = {factory}("])
            if len(field.json_path) == 1:
                lines.append(f"        {field.wire_name!r},")
            else:
                lines.extend(
                    [
                        f"        json_path={field.json_path!r},",
                        f"        criteria_path={field.wire_name!r},",
                    ]
                )
                if field.target:
                    lines.insert(len(lines) - 2, f"        {field.wire_name!r},")
            if not field.target:
                if field.writable:
                    lines.append("        default=None,")
                else:
                    lines.extend(["        writable=False,", "        init=False,"])
                if field.required_on_create:
                    lines.append("        required_on_create=True,")
            lines.append("    )")
        declarations.append("\n".join(lines))
        public[f"models/{entity.module_name}.py"] = (
            '"""User-owned model extensions; this file is never overwritten."""\n\n'
            f"from .._generated.model_bases import {entity.class_name}Base\n\n\n"
            f"class {entity.class_name}({entity.class_name}Base):\n"
            '    """Add shop-specific fields and methods here."""\n'
        )
    prelude = HEADER + "\nfrom __future__ import annotations\n\n"
    if "datetime" in extras:
        prelude += "from datetime import datetime\n"
    if "Any" in extras:
        prelude += "from typing import Any\n"
    if extras:
        prelude += "\n"
    prelude += "from shopware_admin import (\n"
    prelude += "".join(f"    {name},\n" for name in sorted(imports)) + ")\n\n\n"
    source = prelude + "\n\n\n".join(declarations) + "\n"
    if public_imports:
        source += "\n\n# Delay public module imports until every base is defined.\n"
        source += "\n".join(sorted(public_imports)) + "\n"
    generated["_generated/model_bases.py"] = source
    if context:
        source = HEADER + "\nfrom shopware_admin import Context, entity_set\n\n"
        source += "".join(
            f"from ..models.{entity.module_name} import {entity.class_name}\n"
            for entity in sorted(named, key=lambda item: item.module_name)
        )
        source += f"\n\nclass {context}Base(Context):\n"
        source += "".join(
            f"    {entity.set_name} = entity_set({entity.class_name})\n" for entity in named
        )
        generated["_generated/context_base.py"] = source
        public["context.py"] = (
            '"""User-owned context extensions; this file is never overwritten."""\n\n'
            f"from ._generated.context_base import {context}Base\n\n\n"
            f"class {context}({context}Base):\n"
            '    """Add queries, action helpers, or additional entity sets here."""\n'
        )
    for path, content in {**generated, **public}.items():
        try:
            ast.parse(content, filename=path)
        except SyntaxError as error:
            raise ScaffoldError(f"Invalid generated Python in {path}: {error.msg}") from error
    names = {
        entity.spec.name: {
            "class_name": entity.class_name,
            "module_name": entity.module_name,
            "set_name": entity.set_name,
            "fields": {field.wire_name: name for name, field in entity.fields},
        }
        for entity in named
    }
    manifest: Json = {
        "owner": OWNER,
        "format": 1,
        "generator_version": __version__,
        "runtime_requirement": RUNTIME_REQUIREMENT,
        "package": package,
        "context": context,
        "entities": names,
        "schema_hashes": schema_hashes or {},
        "generated": {path: digest(content) for path, content in sorted(generated.items())},
        "public": sorted(public),
    }
    generated[MANIFEST] = json_text(manifest)
    return FilePlan(generated, public, manifest, tuple(diagnostics))
